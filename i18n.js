function arcaT(key, ...args) {
  let text = ARCA_DICTS[ARCA_LANG][key] ?? ARCA_DICTS.es[key] ?? key;
  args.forEach((arg, index) => {
    text = text.replaceAll(`{${index}}`, arg);
  });
  return text;
}
